///////////////////////////////////
// Dockable — dock-toggle mechanics (see DOCKING.md), extracted out of List
// so any view can be dockable, not just List/Grid/Tile. Originally these
// methods lived directly on List; ShiftReportForm and TaskForm are bespoke
// El subclasses (not Lists — see their own file-level comments for why),
// which meant they silently had no dock icon at all despite mounting inside
// a [scoop_dock] like every other shortcode. Every shortcode is expected to
// be dockable, so this is the shared base both List and those bespoke views
// now extend instead of El directly.
//
// A concrete subclass must, before calling _bindDockToggle():
//   - build this.el(...) content and set this.target to the host DOM node
//     passed in by mountAllGrids (List does this in its own constructor)
//   - set this.modelInstance to something with icon/displayTitle/dockTarget/
//     canvasMode (any BaseGridModel already has all four — see that class's
//     constructor)
//   - set this.api (only used for _controlId() in _syncDockHash)
//   - set this.name
//   - build this.TOGGLE = this._buildToggleButton() and append it as a
//     direct child of this.target, alongside whatever content node holds
//     the view's real UI (see css.css's ".in-dock .scoop-grid > form" show/
//     hide rule — a non-<form> content root needs a matching selector added
//     there, same as .task-form)
// then call this._bindDockToggle() once, and optionally
// this._bindPageStatusToggle() if the subclass tracks a pageStatusId.
//////////////////////////////////
import El from "./_el.js";
import PageStatus from "./page-status.js";
import HashState from "../data/hash-state.js";

export default class Dockable extends El {

  // Icon-font class prefix generated by icon-font-generator (see the
  // `npx icon-font-generator ... -p si` command documented in
  // includes/enqueue.php's scoop_enqueue_assets()). One constant here is the
  // only place that prefix is spelled out — a type's 'icon' config only ever
  // carries the "if:<name>" marker, never the raw CSS class, so this is the
  // one place to touch if the generator's -p flag ever changes.
  static ICON_FONT_CSS_PREFIX = 'si-';
  static ICON_FONT_MARKER = 'if:';

  // Below this viewport width, .in-dock's .canvas shows at most one open
  // control at a time (see _enforceCanvasExclusivity below) — a separate,
  // narrower breakpoint than <aside>'s own take-over-100%-width one in
  // css.css (32rem); the two aren't related, they just both key off
  // viewport width.
  static CANVAS_SINGLE_OPEN_BREAKPOINT = '24rem';

  // Maps a model's `dockTarget` value to the :scope-relative selector for
  // its shared slot within .in-dock — see dockToggle() below and
  // _closeSlotSiblings() below, the two places that need to agree on what
  // a "slot" is. Add an entry here (plus the matching element in
  // [scoop_dock]'s markup, includes/shortcode.php) to introduce a new slot.
  static DOCK_SLOT_SELECTORS = {
    action: ':scope > .action-target',
    aside: ':scope > aside',
  };

  // Escape closes ONE open dock control at a time: .action-target's (if
  // occupied) first, then <aside>'s, then whichever .canvas control is
  // earliest in DOM order — .canvas is a plain flex-wrap row with no
  // `order` overrides (see css.css), so DOM order is left-to-right visual
  // order, same as the toolbar's own shortcode-order convention (see
  // DOCKING.md). Only one close per keypress, so repeated Escapes step
  // back through whatever's open instead of clearing the whole dock at
  // once. Bound once globally (see app.js), not per-instance — every
  // dockable view's host already carries the same _dockListInstance
  // back-reference dockToggle() sets below, regardless of which concrete
  // class (List, IframePanel, PopularPlot, ShiftReportForm/TaskForm — the
  // last two borrow _setToggled/_syncDockHash the same way IframePanel
  // does) actually owns it.
  static bindEscapeToClose() {
    document.addEventListener('keydown', (e) => {
      // defaultPrevented catches FindIt's own Escape handler (closes its
      // dropdown, calls preventDefault but not stopPropagation) — without
      // this, dismissing an autocomplete list would also collapse the
      // whole panel underneath it in the same keypress.
      if (e.key !== 'Escape' || e.defaultPrevented) return;

      const dock = document.querySelector('.in-dock');
      if (!dock) return;

      // Yields to anything more locally contextual already open — a
      // confirm/flavor-picker modal (.modal.show) or a Details drill-down
      // (.DETAILS/.DETAILS2.show). Neither of those calls
      // preventDefault()/stopPropagation() on its own Escape handler
      // (confirm-swap-modal.js/flavor-picker-modal.js/details.js), so
      // without this explicit check both would close in the same keypress
      // as a dock panel instead of the modal/drill-down alone winning it.
      if (document.querySelector('.modal.show, .DETAILS.show, .DETAILS2.show')) return;

      const closeHost = (host) => {
        const instance = host?._dockListInstance;
        if (!instance) return false;
        instance._setToggled(false);
        instance._syncDockHash();
        return true;
      };

      const closed =
        closeHost(dock.querySelector(`${Dockable.DOCK_SLOT_SELECTORS.action} > .toggled`)) ||
        closeHost(dock.querySelector(`${Dockable.DOCK_SLOT_SELECTORS.aside} > .toggled`)) ||
        closeHost(dock.querySelector(':scope > .canvas > .toggled'));

      if (closed) e.preventDefault();
    });
  }

  // Wires the host's back-reference, canvas-sizing dataset, and the TOGGLE
  // click handler. Call once, after this.target/this.TOGGLE/this.modelInstance
  // are all set.
  _bindDockToggle() {
    // Internal back-reference from the host DOM node to its owning
    // instance — lets a sibling control (see _closeSlotSiblings) reach this
    // one's own TOGGLE button after dockToggle() has moved that button
    // somewhere else in the tree (the .toolbar), where plain DOM traversal
    // from the host element can no longer find it.
    this.target._dockListInstance = this;

    // Only meaningful within .in-dock's .canvas (see the "canvas" sizing
    // rules in css.css and _enforceCanvasExclusivity() below) — harmless to
    // set unconditionally outside a dock, nothing there selects on it.
    this.target.dataset.canvasMode = this.modelInstance?.canvasMode ?? 'half-stack';

    // Bound to TOGGLE directly, not delegated through this.target —
    // dockToggle() can relocate TOGGLE outside this.target's subtree (into
    // the shared .in-dock .toolbar), where a this.target-scoped listener
    // would never see its clicks bubble through.
    this.TOGGLE.addEventListener("click", (e) => {
      const isOpen = !this.target.classList.contains("toggled");
      this._setToggled(isOpen);
      if (isOpen) this._refreshOnReopen("control re-open");
      this._syncDockHash();

      e.stopPropagation();
    }, true);

    // Per-control refresh button (CONTROL-REFRESH.md §5) — built as TOGGLE's
    // direct sibling so it lands wherever TOGGLE lives... EXCEPT it never
    // rides the shared .toolbar: per Gus's feel-test (2026-09-01), the
    // toolbar holds exactly ONE refresh button (dock chrome's Refresh-all),
    // and each control's own button stays attached to its .scoop-grid host
    // (dockToggle() deliberately does NOT move this one — see there).
    // Data-less views (IframePanel) opt out entirely via dockRefreshEligible=false.
    this.REFRESH = null;
    if (this.dockRefreshEligible !== false) {
      this.REFRESH = this._buildRefreshButton();
      if (this.TOGGLE.parentElement) {
        this.TOGGLE.parentElement.insertBefore(this.REFRESH, this.TOGGLE);
      } else {
        this.target.append(this.REFRESH);
      }

      this.REFRESH.addEventListener("click", (e) => {
        e.stopPropagation();
        this._refreshOnReopen("refresh button");
      }, true);
    }
  }

  // A click-open (or refresh-button press) on a docked control pulls fresh
  // data for THAT control and repaints it — the on-demand half of
  // CONTROL-REFRESH.md (§4 reopen, §5 buttons). Scoped to this control's own
  // entry in scoop_bundle_specs() (`types: [this.name]`), NOT
  // scopedRefreshTypes(): that helper is write-oriented (SCOOP.refreshScope's
  // writesPods) and falls back to the full page union for any read-only
  // trigger, which is backwards for "refresh THIS view" — a control's own
  // bundle spec is both minimal and authoritative for what it displays.
  //
  // The 1s version poll (ScoopAPI.watchForDataChanges) usually means this
  // confirms already-fresh data cheaply (warm cache between saves); its real
  // job is guaranteeing freshness when the tab was hidden (poll skipped) or
  // the poll is in backoff. Failures already toast via refreshPageDomain's
  // own catch, so the rethrow is swallowed here.
  //
  // `cause` feeds PageStatus.setTrigger() via info.name, so the status pill
  // says whether a fetch came from a re-open or the button.
  _refreshOnReopen(cause = "control re-open") {
    // Dock controls only — the requirement (and the buttons) are about dock
    // chrome; an undocked page keeps plain browser-refresh. (The buttons
    // only render usefully docked anyway — see _buildRefreshButton.)
    if (!this.target.closest(".in-dock")) return;
    if (!this.api) return;

    // Mount-time guard: dockToggle()'s hash-restore path calls _setToggled
    // during mountAllGrids() BEFORE any data has loaded — a fetch there
    // would race and duplicate the initial load (and forced calls arriving
    // mid-flight chain serially: N restored controls → N+1 cold fetches on
    // every page open). The restore path reaches _setToggled directly and
    // never calls this method, so this line is belt-and-suspenders only —
    // but a fetch before the initial domain exists is meaningless anyway.
    if (this.api._domain === null) return;

    this.api.refreshPageDomain({
      force: true,
      types: [this.name],
      info: { name: cause },
      demandRepaint: true, // explicit user request — bypasses the per-grid diff gate
    }).catch(() => {});
  }

  // Companion to _buildToggleButton() — same shell conventions (icon-font
  // glyph via the ICON_FONT_MARKER shape, class-prefixed by
  // ICON_FONT_CSS_PREFIX; see the icon-font pipeline in DOCKING.md for how
  // the 'refresh' glyph is generated/committed).
  //
  // Per Gus (2026-09-01 feel-test): the per-control refresh button does NOT
  // ride the shared .toolbar — it stays attached to this control's own host
  // (.scoop-grid), and the toolbar keeps exactly ONE refresh button (the
  // dock chrome's Refresh-all, includes/shortcode.php). Views with no
  // server data at all (IframePanel — ProductionPlan/esr/[scoop_iframe];
  // there is nothing to refresh) declare dockRefreshEligible = false and
  // get no button.
  _buildRefreshButton() {
    const { ICON_FONT_CSS_PREFIX, ICON_FONT_MARKER } = Dockable;
    const raw = this.modelInstance?.displayTitle ?? this.name ?? "";
    // Guard the label: a control whose metadata carried a literal
    // "undefined" string (or nothing) must never render that into the DOM —
    // fall back to the view's logical name instead of trusting the chain.
    const title = `Refresh ${raw && raw !== "undefined" ? raw : this.name || "control"} — fetch current data`;

    const BTN = this.el("button", {
      classes: ["gridRefresh"],
      attrs: { type: "button", title },
    });

    const ICON = this.el("i", {
      classes: ["dockIcon", `${ICON_FONT_CSS_PREFIX}refresh`],
    });

    BTN.append(ICON);
    return BTN;
  }

  // Shared TOGGLE button for Grid/Tile's buildCoreDom() and any bespoke
  // dockable view. Icon is told apart by shape/marker, not a separate
  // config flag (see displayTitle/icon on BaseGridModel, fed from
  // scoop_client_metadata()'s 'displayTitle'/'icon'):
  //   "<svg ...>...</svg>"  -> inline SVG markup, injected as real markup
  //                            (e.g. pasted from the Streamline VS Code
  //                            extension) — checked first since raw SVG
  //                            markup often contains '/' itself.
  //   "if:<name>"           -> icon-font glyph, see ICON_FONT_MARKER above.
  //   contains '/' or ends  -> image path, rendered as <img>.
  //   in an image extension
  //   anything else         -> literal text/unicode glyph.
  _buildToggleButton() {
    const icon  = this.modelInstance?.icon ?? (this.name ? String(this.name).charAt(0) : '?');
    // Guard against a literal "undefined" string riding in from metadata —
    // it would render verbatim as the dock label (seen on a real dock page
    // 2026-09-01); the view's logical name is the honest fallback.
    const rawTitle = this.modelInstance?.displayTitle ?? this.name ?? '';
    const title = rawTitle && rawTitle !== 'undefined' ? rawTitle : (this.name ?? '');

    const BTN = this.el('button', {
      classes: ['gridToggle'],
      attrs: { type: 'button', title },
    });

    const { ICON_FONT_CSS_PREFIX, ICON_FONT_MARKER } = Dockable;
    const trimmed = icon.trim();

    let ICON;
    if (/^<svg[\s>]/i.test(trimmed)) {
      ICON = this.el('span', { classes: ['dockIcon'], html: trimmed });
    } else if (icon.startsWith(ICON_FONT_MARKER)) {
      const cls = icon.slice(ICON_FONT_MARKER.length);
      ICON = this.el('i', { classes: ['dockIcon', `${ICON_FONT_CSS_PREFIX}${cls}`] });
    } else if (/\//.test(icon) || /\.(png|jpe?g|gif|svg|webp)$/i.test(icon)) {
      ICON = this.el('img', { classes: ['dockIcon'], attrs: { src: icon, alt: '' } });
    } else {
      ICON = this.el('span', { classes: ['dockIcon'], text: icon });
    }

    const LABEL = this.el('span', { classes: ['dockTitle'], text: title });

    BTN.append(ICON, LABEL);
    return BTN;
  }

  // Opt-in docking: if this control's host sits inside an .in-dock ancestor
  // (see [scoop_dock] in includes/shortcode.php), move TOGGLE out of the
  // host and into the dock's shared .toolbar row. Called post-mount (see
  // app.js) rather than from the constructor so every docked control's
  // button lands in the toolbar in the same pass, in shortcode order.
  // No-op for controls that aren't inside a dock — they keep TOGGLE exactly
  // where it was originally attached.
  dockToggle() {
    const dock = this.target.closest('.in-dock');
    if (!dock) return;

    const toolbar = dock.querySelector(':scope > .toolbar');
    if (!toolbar || toolbar.contains(this.TOGGLE)) return;

    toolbar.append(this.TOGGLE);
    this.target.classList.add('docked');

    // 'target' => 'action' | 'aside' (see _config.php / DOCKING.md) — this
    // control's whole host, not just its toggle button, lives in one of the
    // dock's shared "slots" instead of .canvas, one shared slot per name so
    // only one control from a given slot is ever mounted there at a time
    // (see _closeSlotSiblings()). Applies to any dockable view (List or
    // bespoke), not just table grids. Slots are peers of .toolbar (not
    // nested inside it — see the CSS docking section for why), so they're
    // looked up from `dock`, same as .toolbar above.
    const slotSelector = Dockable.DOCK_SLOT_SELECTORS[this.modelInstance?.dockTarget];
    if (slotSelector) {
      const slot = dock.querySelector(slotSelector);
      if (slot && !slot.contains(this.target)) {
        slot.append(this.target);
      }
    }

    // Restore open/closed state from a shared link's #dock= hash (see
    // DOCKING.md's "State model") — runs once, synchronously, before this
    // control's rows are ever painted, so there's no flash of the default
    // (closed) state. Only ever opens: the DOM's default is already closed,
    // so a control's ID simply not being listed means "stay closed", same
    // as any fresh mount. _setToggled() below still runs the normal
    // exclusivity rules, so a stale/hand-edited hash listing two
    // same-slot controls self-corrects to whichever mounts last.
    const openIds = (HashState.get('dock') ?? '').split(',').filter(Boolean);
    if (openIds.includes(this.api?._controlId?.(this.target))) {
      this._setToggled(true);
    }

    // Deliberately NOT calling _syncDockHash() here. mountAllGrids() calls
    // dockToggle() on every host sequentially, in one synchronous pass
    // before any is fully "open" — syncing here would overwrite the
    // still-being-built hash with a partial view (only the controls
    // processed so far, not the full set the hash describes and every
    // later dockToggle() call still needs a chance to read it). mountAllGrids
    // does one _syncDockHash() call after the whole pass instead; the TOGGLE
    // click handler still calls _syncDockHash() itself right after
    // _setToggled() — that path is a single real-time user action, not
    // a batch of them.
  }

  // Shared by the TOGGLE click handler and dockToggle()'s hash-restore path
  // — one place that applies a new open/closed state plus the exclusivity
  // rules that go with it (at most one open control per slot, 'nostack'
  // eviction), so restoring from a hash on load behaves identically to a
  // real click.
  _setToggled(isOpen) {
    this.target.classList.toggle("toggled", isOpen);
    this.TOGGLE.classList.toggle("active", isOpen);
    if (isOpen) this._closeSlotSiblings();
    this._enforceCanvasExclusivity();

    // Mirrors .toggled onto the shared slot itself (.action-target or
    // <aside> — see DOCK_SLOT_SELECTORS), not just this.target — see the
    // click handler's original comment on why (css.css's <aside>
    // min/max-width rules need a plain classname to key off).
    this.target.closest('.action-target, aside')?.classList.toggle('active', isOpen);
  }

  // Re-derives #dock= from whatever's actually .toggled right now, rather
  // than patching the hash incrementally — a single click can close OTHER
  // controls too (slot/nostack exclusivity), so a full resync is the only
  // way to keep the hash matching reality without duplicating that logic
  // here. No-op outside a dock (undocked controls don't participate).
  _syncDockHash() {
    const dock = this.target.closest('.in-dock');
    if (!dock) return;

    const openIds = [...dock.querySelectorAll('.scoop-grid.toggled')]
      .map(el => this.api?._controlId?.(el))
      .filter(Boolean);

    HashState.set('dock', openIds.join(','));
  }

  // Within one slot (.action-target or <aside> — see DOCK_SLOT_SELECTORS),
  // only one control's form should be visible at a time — called when THIS
  // control's toggle just opened (see the TOGGLE click listener above).
  // Closes any other already-open sibling sharing the same slot, via the
  // back-reference dockToggle() left on the host (target._dockListInstance)
  // — the sibling's own TOGGLE button no longer lives near its host once
  // docked, so plain DOM traversal from here can't find it any other way.
  _closeSlotSiblings() {
    const slot = this.target.closest('.action-target, aside');
    if (!slot) return;

    for (const sibling of slot.children) {
      if (sibling === this.target || !sibling.classList.contains('toggled')) continue;

      sibling.classList.remove('toggled');
      sibling._dockListInstance?.TOGGLE?.classList.remove('active');
    }
  }

  // Two independent reasons a .canvas control needs every OTHER open
  // control closed:
  //  - 'nostack' canvasMode (see BaseGridModel's canvasMode comment and the
  //    "canvas" sizing rules in css.css — currently just ItemPivot,
  //    'full-nostack') expects the whole .canvas, not just its own row/
  //    column: nothing else should be open alongside it, in either
  //    direction — opening one closes every other open .canvas control,
  //    and opening any OTHER control while a nostack one is already open
  //    closes that nostack control too.
  //  - Below CANVAS_SINGLE_OPEN_BREAKPOINT, .canvas has no room for more
  //    than one open control regardless of canvasMode — same "close every
  //    other one" behavior, just keyed off the viewport instead of the
  //    type. Plain 'stack'/'half' controls above that width never trigger
  //    this and keep coexisting normally.
  // Only called from the TOGGLE click handler, and only relevant for
  // controls that stay in .canvas (dockTarget routes a control into a slot
  // instead, where _closeSlotSiblings() above is the equivalent
  // exclusivity rule).
  _enforceCanvasExclusivity() {
    const canvas = this.target.closest('.canvas');
    if (!canvas) return;

    const isNostack = !!this.modelInstance?.canvasMode?.endsWith('nostack');
    const hasOpenNostack = [...canvas.children].some(el =>
      el !== this.target
      && el.classList.contains('toggled')
      && el._dockListInstance?.modelInstance?.canvasMode?.endsWith('nostack')
    );
    const isNarrowViewport = window.matchMedia(
      `(max-width: ${Dockable.CANVAS_SINGLE_OPEN_BREAKPOINT})`
    ).matches;
    if (!isNostack && !hasOpenNostack && !isNarrowViewport) return;

    for (const sibling of canvas.children) {
      if (sibling === this.target || !sibling.classList.contains('toggled')) continue;

      sibling.classList.remove('toggled');
      sibling._dockListInstance?.TOGGLE?.classList.remove('active');
    }
  }

  // Mirrors this control's PageStatus freshness onto its own TOGGLE button —
  // dockToggle() moves TOGGLE into the shared dock toolbar, so this is what
  // makes a collapsed panel's loading/fetching state visible without opening
  // it. Falls back to this.target's id (PopularPlot borrows this method but
  // never sets this.pageStatusId — see popular-plot.js) since that's the
  // same id ScoopAPI registered the host under either way.
  _bindPageStatusToggle() {
    const id = this.pageStatusId ?? this.target?.id;
    if (!id || !this.TOGGLE) return;

    // Both toolbar buttons reflect THIS control's load state (see
    // CONTROL-REFRESH.md §5) — TOGGLE has always shown the fetching ring;
    // REFRESH joins the same treatment so whichever button the user's eye
    // is on shows that a fetch is running and how far along it is.
    const statusBtns = () => [this.TOGGLE, this.REFRESH].filter(Boolean);

    const apply = (state) => {
      for (const btn of statusBtns()) {
        btn.classList.toggle('loading', state === 'unknown');
        btn.classList.toggle('fetching', state === 'fetching');
        // Leaving 'fetching' mid-countdown (fresh/stale landing) — clear the
        // ring rather than leave it stuck at whatever % it last reached.
        if (state !== 'fetching') {
          btn.style.removeProperty('--eta-progress');
          btn.classList.remove('overtime');
        }
      }
    };
    apply(PageStatus.getState(id));

    this._onPageStatusChange = (e) => {
      if (e.detail?.id === id) apply(e.detail.state);
    };
    document.addEventListener('ts:page-status:change', this._onPageStatusChange);

    // Same conic-gradient ring PAGE-STATUS's own cache-bust <em> shows (see
    // css.css's .cache-bust.counting-down and this TOGGLE's own .fetching
    // rules). PageStatus can time more than one load concurrently now (see
    // page-status.js's _loads map — analytics types self-fetch alongside the
    // shared bundle fetch, not sequentially before it), so a tick's own
    // e.detail.ids is what scopes this to THIS grid's load specifically —
    // checking only the 'fetching' class isn't enough on its own, since a
    // *different* concurrent load's ticks would otherwise paint this ring
    // with the wrong grid's progress.
    this._onPageStatusProgress = (e) => {
      if (!e.detail.ids.includes(id)) return;
      for (const btn of statusBtns()) {
        btn.style.setProperty('--eta-progress', e.detail.progressPct.toFixed(2));
        btn.classList.toggle('overtime', e.detail.overtime);
      }
    };
    document.addEventListener('ts:page-status:progress', this._onPageStatusProgress);
  }
}
